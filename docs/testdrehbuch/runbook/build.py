def chip(p):
    name, col = PERS[p]
    return f'<span class="chip" style="--c:{col}">{p if p != "alle" else "alle"}</span>'

def chips(s):
    return " ".join(chip(p.strip()) for p in s.split(",")) if s else ""

def esc(t):
    # **fett** und `code` erlauben
    t = html.escape(t)
    import re
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"`(.+?)`", r"<code>\1</code>", t)
    return t

