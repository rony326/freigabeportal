def szen_html(s):
    sid, titel, wer, dauer, ziel, vor, schritte = s
    rows = []
    for i, (p, schritt, erw) in enumerate(schritte, 1):
        ps = " ".join(chip(x.strip()) for x in p.replace("/", ",").split(",")) if p else ""
        rows.append(f'<tr><td class="nr">{i}</td><td class="wer">{ps}</td>'
                    f'<td>{esc(schritt)}</td><td class="erw">{esc(erw) if erw else "—"}</td>'
                    f'<td class="ok"><span class="box"></span> ok<br><span class="box"></span> Fehler</td></tr>')
    vor_html = f'<p class="vor"><b>Voraussetzung:</b> {esc(vor)}</p>' if vor else ""
    return f'''
<section class="szen">
  <header><span class="sid">{sid}</span><h3>{esc(titel)}</h3><span class="meta">{chips(wer)} <span class="dauer">{dauer}</span></span></header>
  <p class="ziel">{esc(ziel)}</p>
  {vor_html}
  <table class="steps"><thead><tr><th>#</th><th>Wer</th><th>Schritt</th><th>Erwartet</th><th>Ergebnis</th></tr></thead>
  <tbody>{"".join(rows)}</tbody></table>
  <div class="notiz">Notizen / Nummer des Vorgangs: </div>
</section>'''

def uebersicht():
    rows = []
    for bid, btitel, _, sz in BLOECKE:
        for s in sz:
            rows.append(f'<tr><td><span class="box"></span></td><td class="mono">{s[0]}</td><td>{esc(s[1])}</td><td>{chips(s[2])}</td><td>{s[3]}</td></tr>')
    return "".join(rows)

